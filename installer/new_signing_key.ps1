<#
  Creates the RSA key pair that signs update manifests.
    - private key  -> installer\signing\lumora_update_private.xml   (KEEP SECRET, back it up; never publish it)
    - public key   -> lib\services\update_key.dart                   (compiled into the app)
  Run once. Re-running replaces the key: apps built with the old key will reject new updates.
#>
$ErrorActionPreference = 'Stop'
$priv = Join-Path $PSScriptRoot 'signing\lumora_update_private.xml'
if (Test-Path $priv) { throw "Ya existe $priv. Bórrala solo si quieres rotar la clave (las versiones ya instaladas dejarán de aceptar actualizaciones)." }
$rsa = New-Object Security.Cryptography.RSACryptoServiceProvider 3072
$rsa.PersistKeyInCsp = $false
New-Item -ItemType Directory -Force (Split-Path $priv) | Out-Null
[IO.File]::WriteAllText($priv, $rsa.ToXmlString($true), (New-Object Text.UTF8Encoding($false)))
$p = $rsa.ExportParameters($false)
$n = [Convert]::ToBase64String($p.Modulus); $e = [Convert]::ToBase64String($p.Exponent)
$dart = @"
// Generated by installer\new_signing_key.ps1 - public half of the update-signing key.
const updateKeyModulus = '$n';
const updateKeyExponent = '$e';
"@
[IO.File]::WriteAllText((Join-Path $PSScriptRoot '..\lib\services\update_key.dart'), $dart, (New-Object Text.UTF8Encoding($false)))
Write-Host 'Clave creada. Guarda una copia de signing\lumora_update_private.xml en un sitio seguro.'
