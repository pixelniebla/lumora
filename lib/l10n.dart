/// Translated string lookup. Missing keys fall back to Spanish, then to the key.
extension Tr on BuildContext {
  String tr(String key, {Map<String, String> args = const {}}) {
    // select: only rebuild when the language changes, not on every state update.
    final lang = select<AppState, String>((s) => s.lang);
    return translate(lang, key, args: args);
  }
}

String translate(String lang, String key, {Map<String, String> args = const {}}) {
  var s = _t[lang]?[key] ??
      extraStrings[lang]?[key] ??
      moreStrings[lang]?[key] ??
      _t['es']![key] ??
      extraStrings['es']![key] ??
      moreStrings['es']![key] ??
      key;
  args.forEach((k, v) => s = s.replaceAll('{$k}', v));
  return s;
}

/// User-facing text for a caught error: translated when it is a [LocalizedError],
/// otherwise the raw message with any credentials stripped.
String errorText(String lang, Object e) {
  if (e is LocalizedError) return translate(lang, e.key, args: e.args);
  return Log.redact(e.toString().replaceFirst('Exception: ', ''));
}

/// Translates a checker detail code ('bad_playlist', ...) if it is one; otherwise returns it redacted.
String detailText(String lang, String detail) {
  final known = _t[lang]?.containsKey(detail) == true || extraStrings[lang]?.containsKey(detail) == true;
  return known ? translate(lang, detail) : Log.redact(detail);
}

