String formatDate(String lang, DateTime d) {
  final day = _days[lang]![d.weekday - 1];
  final month = _months[lang]![d.month - 1];
  return switch (lang) {
    'en' => '$day, $month ${d.day}',
    'fr' => '$day ${d.day} $month',
    _ => '$day, ${d.day} de $month',
  };
}

